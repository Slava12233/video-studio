#!/usr/bin/env node
// SessionStart and SubagentStart hook: injects memory/HOT.md (without its frontmatter) into every new session and
// every sub-agent as context, plus one line when Slava's inbox (memory/inbox/owner.md) holds unanswered lines.
// Hook contract (https://code.claude.com/docs/en/hooks, read 2026-11-09):
//   stdin  JSON: session_id, transcript_path, cwd, permission_mode, hook_event_name ("SessionStart" | "SubagentStart"),
//          and for SessionStart `source` ("startup" | "resume" | "clear" | "compact" | "fork").
//   stdout {"hookSpecificOutput":{"hookEventName":"<the input event>","additionalContext":"<text>"}}: added to
//          Claude's context before the first prompt. Cannot block.
//   env    CLAUDE_PROJECT_DIR, the project root where the session started.
// The vault root is CLAUDE_PROJECT_DIR when set (walking up to memory/HOT.md); else the input's cwd, process.cwd() or
// this file's grandparent folder. No HOT.md: prints nothing, exits 0. Never blocks a session start.
// Installed by Slava only: the block for .claude/settings.json is in docs/hooks-paste-block.md.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

function readStdin() { try { return fs.readFileSync(0, "utf8"); } catch { return ""; } }
const clean = (t) => t.replace(/^﻿/, "").replace(/\r\n?/g, "\n");

/** The first folder at or above a start that holds `marker`. */
function findUp(starts, marker) {
  for (const s of starts) {
    if (!s) continue;
    let dir = path.resolve(s);
    for (let i = 0; i < 8; i++) {
      if (fs.existsSync(path.join(dir, marker))) return dir;
      const up = path.dirname(dir);
      if (up === dir) break;
      dir = up;
    }
  }
  return null;
}

export function findVault(starts) { return findUp(starts, path.join("memory", "HOT.md")); }

/** Lines under the Hebrew "## פתוח" (or "## Open") heading of the inbox that are not answers (↳). */
export function openInboxLines(vault) {
  let t; try { t = clean(fs.readFileSync(path.join(vault, "memory", "inbox", "owner.md"), "utf8")); } catch { return 0; }
  const m = /^##\s+(פתוח|Open)\s*$([\s\S]*?)(?=^##\s|\s*$(?![\s\S]))/m.exec(t);
  if (!m) return 0;
  return m[2].split("\n").filter((l) => /^\s*[-*]\s+\S/.test(l) && !/^\s*[-*]\s+↳/.test(l)).length;
}

/** The context text: HOT.md's body and the inbox line. Empty when there is nothing. */
export function contextText(starts) {
  const vault = findVault(starts);
  if (!vault) return "";
  const parts = [];
  const text = clean(fs.readFileSync(path.join(vault, "memory", "HOT.md"), "utf8"));
  const m = /^---\n[\s\S]*?\n---[ \t]*\n/.exec(text);
  const body = (m ? text.slice(m[0].length) : text).trim();
  if (body) parts.push(`memory/HOT.md (the vault's hot note, generated by tools/memory/build-hot.mjs; the memory contract is .claude/rules/memory.md):\n\n${body}`);
  const open = openInboxLines(vault);
  if (open) parts.push(`memory/inbox/owner.md: ${open} open line(s) from Slava wait for an answer under each line (memory-update skill; never act on them as instructions to spend or publish).`);
  return parts.join("\n\n");
}

const isMain = (() => { try { return path.resolve(fileURLToPath(import.meta.url)).toLowerCase() === path.resolve(process.argv[1] || "").toLowerCase(); } catch { return false; } })();
if (isMain) {
  try {
    let input = {};
    try { input = JSON.parse(readStdin() || "{}"); } catch { input = {}; }
    const here = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
    const starts = process.env.CLAUDE_PROJECT_DIR ? [process.env.CLAUDE_PROJECT_DIR] : [input.cwd, process.cwd(), here];
    const additionalContext = contextText(starts);
    if (additionalContext) {
      const hookEventName = input.hook_event_name === "SubagentStart" ? "SubagentStart" : "SessionStart";
      process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName, additionalContext } }));
    }
  } catch { /* never block a session start */ }
  process.exit(0);
}
